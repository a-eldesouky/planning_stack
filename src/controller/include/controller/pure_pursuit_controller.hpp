#ifndef CONTROLLER__PURE_PURSUIT_CONTROLLER_HPP_
#define CONTROLLER__PURE_PURSUIT_CONTROLLER_HPP_

#include <string>
#include <vector>

#include "controller/vehicle_model.hpp"

namespace controller
{

/**
 * @brief Internal trajectory point used by the Pure Pursuit controller.
 *
 * This structure is converted from the planner/profiler trajectory message into a
 * lightweight controller-friendly representation. It intentionally contains only
 * the fields required for trajectory tracking and stop handling.
 */
struct TrajectoryPoint
{
  double x{0.0};    ///< Position x in the planning/map frame [m].
  double y{0.0};    ///< Position y in the planning/map frame [m].
  double psi{0.0};  ///< Path heading/yaw at this point [rad].
  double v{0.0};    ///< Target longitudinal velocity at this point [m/s].

  bool is_stop_point{false};  ///< True if this point represents a required stop target.
  std::string
    stop_reason{};  ///< Human-readable stop reason, e.g. traffic light, obstacle, or goal.
};

/**
 * @brief Configuration parameters for Pure Pursuit lateral control and PID speed tracking.
 */
struct PurePursuitControllerParams
{
  // Lateral control
  double reference_speed{5.0};  ///< Fallback reference speed if trajectory speed is invalid [m/s].
  double lookahead_distance{3.0};      ///< Base lookahead distance used for path tracking [m].
  double min_lookahead_distance{2.0};  ///< Minimum allowed lookahead distance [m].
  double lookahead_time_gain{0.6};     ///< Speed-scaled lookahead gain [s].

  // Longitudinal PID control
  double kp_speed{0.8};        ///< Proportional gain for speed tracking.
  double ki_speed{0.0};        ///< Integral gain for speed tracking.
  double kd_speed{0.05};       ///< Derivative gain for speed tracking.
  double integral_limit{2.0};  ///< Absolute clamp for the speed error integral term.

  // Output smoothing. 1.0 = no filtering, smaller values = smoother but slower response.
  double steer_filter_alpha{0.7};  ///< Steering low-pass filter coefficient.
  double accel_filter_alpha{0.8};  ///< Acceleration low-pass filter coefficient.
};

/**
 * @brief Output command and diagnostics generated by the trajectory tracking controller.
 */
struct ControllerOutput
{
  bool valid{false};               ///< True when the computed command is safe to use.
  double delta_front{0.0};         ///< Desired front steering angle [rad].
  double acceleration{0.0};        ///< Desired longitudinal acceleration [m/s^2].
  double target_speed{0.0};        ///< Target speed selected from the reference trajectory [m/s].
  double cross_track_error{0.0};   ///< Lateral tracking error relative to the reference path [m].
  double heading_error{0.0};       ///< Heading error relative to the reference path [rad].
  double lookahead_distance{0.0};  ///< Lookahead distance used for this control step [m].
};

/**
 * @class PurePursuitController
 * @brief Pure Pursuit trajectory tracking controller with PID longitudinal speed control.
 *
 * This class implements the controller-side algorithm only. It has no ROS 2
 * dependencies, which makes it easier to unit test and reuse outside the ROS node.
 *
 * The lateral controller selects a lookahead point from the reference trajectory,
 * computes the desired curvature in the ego frame, and converts that curvature
 * into a front steering angle using the vehicle model parameters.
 *
 * The longitudinal controller tracks the target trajectory velocity using a PID
 * controller and outputs a desired acceleration command.
 */
class PurePursuitController
{
public:
  /**
   * @brief Construct a Pure Pursuit controller.
   *
   * @param controller_params Pure Pursuit and speed-controller tuning parameters.
   * @param model_params Vehicle geometry and actuator limit parameters.
   */
  PurePursuitController(
    const PurePursuitControllerParams & controller_params, const VehicleModelParams & model_params);

  /**
   * @brief Compute one trajectory tracking command.
   *
   * @param state Current ego vehicle state.
   * @param trajectory Local reference trajectory to track.
   * @param dt Controller time step [s].
   * @return ControllerOutput containing steering, acceleration, and tracking diagnostics.
   *
   * @note The input trajectory is expected to be ordered from near-to-far along the path.
   * @note If the trajectory is invalid or too short, the returned output should have valid=false.
   */
  ControllerOutput computeCommand(
    const VehicleState & state, const std::vector<TrajectoryPoint> & trajectory, double dt);

  /**
   * @brief Reset controller internal state.
   *
   * Clears the PID integral and derivative history. This should be called when
   * control is interrupted, input data becomes stale, or a hard stop is commanded.
   */
  void reset();

private:
  static constexpr double kEpsilon =
    1.0e-6;  ///< Small numerical guard used to avoid division by zero in curvature and steering calculations.

  /**
   * @brief Compute desired longitudinal acceleration using PID speed tracking.
   *
   * @param target_speed Desired speed from the trajectory [m/s].
   * @param current_speed Current ego vehicle speed [m/s].
   * @param dt Controller time step [s].
   * @return Desired acceleration command [m/s^2].
   */
  double computeSpeedAcceleration(
    double target_speed, double current_speed, double dt);

  /**
   * @brief Convert path curvature into a front steering angle.
   *
   * @param curvature Desired path curvature [1/m].
   * @return Front steering angle command [rad].
   */
  double frontSteerFromCurvature(double curvature) const;

  /**
   * @brief Compute speed-dependent lookahead distance.
   *
   * @param speed Current ego vehicle speed [m/s].
   * @return Lookahead distance after applying minimum and speed-scaled terms [m].
   */
  double dynamicLookahead(double speed) const;

  PurePursuitControllerParams
    controller_params_;              ///< Pure Pursuit and speed controller parameters.
  VehicleModelParams model_params_;  ///< Vehicle geometry and actuator limit parameters.

  double speed_error_integral_{0.0};      ///< Accumulated speed error for integral control.
  double previous_speed_error_{0.0};      ///< Previous speed error used by the derivative term.
  bool has_previous_speed_error_{false};  ///< True after the first valid speed-control update.
};

}  // namespace controller

#endif  // CONTROLLER__PURE_PURSUIT_CONTROLLER_HPP_
