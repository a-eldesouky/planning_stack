#ifndef MISSION_PLANNER__MISSION_PLANNER_NODE_HPP_
#define MISSION_PLANNER__MISSION_PLANNER_NODE_HPP_

#include <geometry_msgs/msg/pose_stamped.hpp>
#include <geometry_msgs/msg/quaternion.hpp>
#include <memory>
#include <nav_msgs/msg/odometry.hpp>
#include <nav_msgs/msg/path.hpp>
#include <rclcpp/rclcpp.hpp>

#include "mission_planner/mission_planner.hpp"
#include "planning_msgs/msg/route.hpp"

namespace mission_planner
{

/**
 * @class MissionPlannerNode
 * @brief ROS2 node wrapper around MissionPlanner.
 *
 * Bridges the pure C++ MissionPlanner with the ROS2 ecosystem:
 * - Subscribes to ego vehicle odometry for current pose
 * - Subscribes to RViz2 goal pose to trigger planning
 * - Publishes the planned route as planning_msgs/Route for downstream consumption
 * - Also publishes a nav_msgs/Path for RViz2 visualization of the route
 *
 * ## Topics
 * Subscribed:
 * - `/carla/ego_vehicle/odometry`  (nav_msgs/msg/Odometry)
 *   Current vehicle pose and heading in map frame.
 *
 * - `/goal_pose`  (geometry_msgs/msg/PoseStamped)
 *   Goal pose from RViz2 "2D Goal Pose" tool. Position is the
 *   click point, orientation is the drag direction. Triggers planning.
 *
 * Published:
 * - `/mission_planner/route`  (planning_msgs/msg/Route)
 *   Planned global route as an ordered sequence of waypoints with metadata.
 *   Republished on every successful plan.
 *
 * - `/mission_planner/route_display`  (nav_msgs/msg/Path)
 *   Planned global route as an ordered sequence of PoseStamped waypoints
 *   in map frame. Republished on every successful plan.
 *
 * ## Parameters
 * - `hd_map_path`  (string, required)
 *   Absolute path to hd_map.json generated by the HD map generator.
 */
class MissionPlannerNode : public rclcpp::Node
{
public:
  /**
     * @brief Construct the node, load the HD map, create topics.
     *
     * Reads the `hd_map_path` parameter and constructs MissionPlanner.
     * Throws if the parameter is missing or the map fails to load.
     *
     * @param options  ROS2 node options
     * @throws std::runtime_error if hd_map_path parameter is not set
     * @throws std::runtime_error if MissionPlanner fails to load the map
     */
  explicit MissionPlannerNode(const rclcpp::NodeOptions & options = rclcpp::NodeOptions());

private:
  static constexpr double kDefaultRoadHalfWidth = 4.0;  ///< Default road half-width in metres
  static constexpr double kMinCurvatureDistance = 0.1;  ///< Minimum distance between waypoints
  static constexpr double kMinCurvatureArea = 1e-6;     ///< Ignore nearly collinear points.

  /**
     * @brief Odometry callback: stores latest vehicle pose.
     *
     * Does not trigger planning. Pose is stored and used when the
     * next goal is received.
     *
     * @param msg  Incoming odometry message in map frame
     */
  void onOdometry(const nav_msgs::msg::Odometry::ConstSharedPtr & msg);

  /**
     * @brief Goal pose callback: triggers planning.
     *
     * Called when the user clicks "2D Goal Pose" in RViz2.
     * Extracts position (x, y) and heading from the PoseStamped
     * orientation (drag direction), then calls planAndPublish().
     * Guards against planning before the first odometry arrives.
     *
     * @param msg  Goal pose in map frame from RViz2
     */
  void onGoalPose(const geometry_msgs::msg::PoseStamped::ConstSharedPtr & msg);

  /**
     * @brief Run the planner and publish the route.
     *
     * Extracts position and yaw from last_odom_, calls
     * planner_->plan() with start and goal poses, converts the result
     * to nav_msgs/Path, and publishes on route_pub_.
     * Logs a warning if planning fails and does not publish.
     *
     * @param goal_x            Goal X position in map frame (metres)
     * @param goal_y            Goal Y position in map frame (metres)
     * @param goal_heading_rad  Goal heading from RViz2 drag (radians)
     */
  void planAndPublish(double goal_x, double goal_y, double goal_heading_rad);

  /**
     * @brief Convert a Route to nav_msgs/Path.
     *
     * Flattens all RouteLanelet waypoints into a single ordered
     * sequence of PoseStamped messages with frame_id "map".
     * Heading at each waypoint is encoded as a yaw-only quaternion
     * in the pose orientation field.
     *
     * @param route  Planned route from MissionPlanner
     * @return       nav_msgs/Path ready to publish
     */
  /**
   * @brief Convert a Route to planning_msgs/Route.
   *
   * Preserves all metadata (road_half_width, lane_half_width, curvature)
   * in the RouteLanelet waypoints. Published on /mission_planner/route.
   */
  planning_msgs::msg::Route routeToMsg(const Route & route);

  /**
     * @brief Calculate the road and lane widths at a given position.
     *
     * @param x  X position in map frame (metres)
     * @param y  Y position in map frame (metres)
     * @return   Pair of road and lane widths (metres)
     */
  std::pair<double, double> calculateWidths(
    double x, double y, const std::string & lanelet_id) const;

  /**
   * @brief Calculate curvature at a waypoint given its neighbors.
   *
   * Uses the three-point formula to estimate curvature based on the
   * positions of the previous, current, and next waypoints. Curvature
   * is defined as 1/radius of the osculating circle. Returns 0 for
   * straight segments and higher values for sharper curves.
   *
   * @param prev  Previous waypoint (x, y)
   * @param curr  Current waypoint (x, y)
   * @param next  Next waypoint (x, y)
   * @return      Curvature in 1/metres
   */
  static double calculateCurvature(
    const RoutePoint & prev, const RoutePoint & curr, const RoutePoint & next);

  /**
   * @brief Convert a planning_msgs/Route to nav_msgs/Path for RViz2.
   *
   * Strips all metadata (road_half_width, curvature, etc.) and produces
   * a plain pose sequence. Published on /mission_planner/route_display.
   * Add a Path display in RViz2 and set the topic to see the global route.
   */
  nav_msgs::msg::Path routeToDisplayPath(const planning_msgs::msg::Route & route);

  /**
     * @brief Extract yaw angle from a geometry_msgs quaternion.
     *
     * Converts quaternion (x, y, z, w) to yaw using the standard
     * atan2 formula. Used for both odometry and goal pose orientation.
     *
     * @param q  Quaternion from ROS2 message
     * @return   Yaw angle in radians
     */
  static double quaternionToYaw(const geometry_msgs::msg::Quaternion & q);

  std::unique_ptr<MissionPlanner> planner_;  ///< Owns the mission planner

  rclcpp::Subscription<nav_msgs::msg::Odometry>::SharedPtr odom_sub_;  ///< Odometry subscriber
  rclcpp::Subscription<geometry_msgs::msg::PoseStamped>::SharedPtr
    goal_sub_;                                                         ///< Goal pose subscriber
  rclcpp::Publisher<planning_msgs::msg::Route>::SharedPtr route_pub_;  ///< Route publisher
  rclcpp::Publisher<nav_msgs::msg::Path>::SharedPtr
    route_display_pub_;  ///< /mission_planner/route_display → RViz2

  nav_msgs::msg::Odometry::ConstSharedPtr last_odom_;  ///< Latest odometry message.
};

}  // namespace mission_planner

#endif  // MISSION_PLANNER__MISSION_PLANNER_NODE_HPP_
