"""
mission_planner.launch.py

Launches the MissionPlannerNode and RViz2 for a mission-planner demo.

Usage:
    ros2 launch mission_planner mission_planner.launch.py \
        hd_map_path:=/absolute/path/to/hd_map.json

Prerequisites (must be running before this launch):
    Terminal 1: ./CarlaUE4.sh
    Terminal 2: ros2 launch carla_ros_bridge \
                    carla_ros_bridge_with_example_ego_vehicle.launch.py

Demo workflow:
    1. Launch this file
    2. In RViz2, select "2D Goal Pose" tool (keyboard: G)
    3. Click and drag on the map to set goal position and heading
    4. Watch /mission_planner/route appear as a Path in RViz2
"""

from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.substitutions import LaunchConfiguration, PathJoinSubstitution
from launch_ros.actions import Node
from launch_ros.substitutions import FindPackageShare


def generate_launch_description() -> LaunchDescription:

    hd_map_path_arg = DeclareLaunchArgument(
        name="hd_map_path",
        default_value=PathJoinSubstitution([
            FindPackageShare("hd_map"),
            "maps",
            "Town01_hd_map.json",
        ]),
        description="Absolute path to hd_map.json generated by the HD map generator",
    )

    mission_planner_node = Node(
        package="mission_planner",
        executable="mission_planner_node",
        name="mission_planner_node",
        output="screen",
        parameters=[{
            "hd_map_path": LaunchConfiguration("hd_map_path"),
        }],
        remappings=[
            ("/carla/ego_vehicle/odometry", "/carla/ego_vehicle/odometry"),
            ("/goal_pose",                  "/goal_pose"),
            ("/mission_planner/route",      "/mission_planner/route"),
        ],
    )

    return LaunchDescription([
        hd_map_path_arg,
        mission_planner_node,
    ])