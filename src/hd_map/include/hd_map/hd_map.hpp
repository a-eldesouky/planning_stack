#ifndef HD_MAP__HD_MAP_HPP_
#define HD_MAP__HD_MAP_HPP_

#include <functional>
#include <nlohmann/json.hpp>
#include <string>
#include <unordered_map>
#include <vector>

/**
 * @file hd_map.hpp
 * @brief HD Map data structures and query interface.
 *
 * Provides the HDMap class and all associated data structures used by
 * downstream planning modules (Mission Planner, Behavior Planner,
 * Local Planner). The map is loaded once from a JSON file generated
 * by the Python pipeline and queried at runtime via O(1) lookup tables.
 *
 * ## Coordinate frame
 * All positions are in the ROS `map` frame published by the CARLA ROS bridge
 * (right-handed: CARLA's y axis is negated when the map is generated).
 * Headings are in radians, range [-pi, pi].
 */

namespace hd_map
{

/**
 * @brief A 3D point in the ROS map frame.
 *
 * Used for lane boundary points where heading is not required.
 */
struct Point3D
{
  double x{0.0};  ///< X coordinate in map frame (metres)
  double y{0.0};  ///< Y coordinate in map frame (metres)
  double z{0.0};  ///< Z coordinate in map frame (metres)
};

/**
 * @brief A centerline point with heading information.
 *
 * Extends Point3D with the forward direction of travel at this point.
 */
struct CenterlinePoint
{
  Point3D position;         ///< 3D position of the centerline point
  double heading_rad{0.0};  ///< Forward heading in radians, range [-pi, pi]
};

/**
 * @brief A single drivable lane segment in the HD map.
 *
 * A lanelet represents one directed lane between two points.
 * It carries its geometry (centerline and boundaries), graph
 * connectivity (predecessors, successors, neighbors), and
 * regulatory elements (traffic lights).
 *
 * ## Graph Connectivity
 * - `successors`    : lanelets that can be entered after this one
 * - `predecessors`  : lanelets that lead into this one
 * - `left_neighbor` : parallel lane to the left, for lane changes
 * - `right_neighbor`: parallel lane to the right, for lane changes
 *
 * The Mission Planner uses `successors` as graph edges for A* search.
 * The Local Planner uses `left_neighbor` / `right_neighbor` for lane changes.
 */
struct Lanelet
{
  std::string id;           ///< Unique ID, format: "lanelet_{road_id}_{lane_id}"
  int road_id{0};           ///< CARLA road ID this lanelet belongs to
  int lane_id{0};           ///< CARLA lane ID (negative = right side of road)
  bool is_junction{false};  ///< True if this lanelet is inside a junction
  int junction_id{-1};      ///< Junction ID if is_junction is true, else -1
  double length_m{0.0};     ///< Arc length of centerline in metres

  std::vector<CenterlinePoint> centerline;  ///< Ordered centerline points, entry → exit
  std::vector<Point3D> left_boundary;       ///< Left lane boundary points
  std::vector<Point3D> right_boundary;      ///< Right lane boundary points

  std::vector<std::string> predecessors;  ///< IDs of lanelets that lead into this one
  std::vector<std::string> successors;    ///< IDs of reachable lanelets from this one
  std::string left_neighbor;              ///< ID of left parallel lane, empty if none
  std::string right_neighbor;             ///< ID of right parallel lane, empty if none
};

/**
 * @brief An intersection in the HD map.
 *
 * Junctions connect multiple roads. Each junction carries the IDs of
 * its internal lanelets (the connecting paths through the intersection).
 */
struct Junction
{
  int id{-1};            ///< Unique junction ID from CARLA
  double center_x{0.0};  ///< Junction center X in map frame (metres)
  double center_y{0.0};  ///< Junction center Y in map frame (metres)
  std::string type;      ///< Junction type, e.g. "T_junction", "X_junction"

  std::vector<int> connecting_roads;           ///< IDs of roads meeting at this junction
  std::vector<std::string> internal_lane_ids;  ///< IDs of lanelets inside the junction
};

/**
 * @brief Top-level metadata for the HD map.
 *
 * Populated from the `metadata` section of `hd_map.json`.
 * Provides summary counts and configuration used for validation.
 */
struct MapMetadata
{
  std::string map_name;            ///< Map name, e.g. "Town01"
  std::string version;             ///< Map version string
  std::string format;              ///< Format identifier, e.g. "lanelet2_inspired_json"
  double waypoint_spacing_m{2.0};  ///< Distance between centerline points (metres)
  int total_lanelets{0};           ///< Total number of lanelets in map
  int total_junctions{0};          ///< Total number of junctions in map
};

/**
 * @class HDMap
 * @brief Main HD map class: loads and provides queries over the map.
 *
 * Loads the HD map from a JSON file generated by the Python
 * pipeline. After loading, all data is held in memory with O(1)
 * lookup tables built over lanelet IDs and junction IDs.
 */
class HDMap
{
public:
  HDMap() = default;

  /**
     * @brief Load the HD map from a JSON file.
     *
     * Parses lanelets, junctions, and traffic lights from the JSON,
     * then builds O(1) lookup tables. Safe to call only once:
     * calling load() again on an already-loaded map is undefined.
     *
     * @param json_path  Absolute path to hd_map.json.
     * @return           True on success, false if the file cannot be
     *                   opened or the JSON cannot be parsed.
     */
  [[nodiscard]] bool load(const std::string & json_path);

  /**
     * @brief Returns true if the map was successfully loaded.
     *
     * Always check this before calling any query method.
     */
  bool isLoaded() const { return loaded_; }

  /**
     * @brief Returns top-level map metadata.
     *
     * @return  Const reference to MapMetadata. Valid for the lifetime
     *          of this HDMap instance.
     */
  const MapMetadata & getMetadata() const { return metadata_; }

  /**
     * @brief Returns all lanelets in the map.
     *
     * Iterate over this to build the A* graph or to search all lanelets.
     * The reference is valid for the lifetime of this HDMap instance.
     *
     * @return  Const reference to the internal lanelet vector.
     */
  const std::vector<Lanelet> & getAllLanelets() const;

  /**
     * @brief Find a lanelet by its string ID.
     *
     * O(1) lookup via hash table.
     *
     * @param id    Lanelet ID string, e.g. "lanelet_1_-1".
     * @return      Pointer to the lanelet, or nullptr if not found.
     */
  const Lanelet * getLaneletById(const std::string & id) const;

  /**
     * @brief Find the lanelet whose centerline is geometrically closest to (x, y).
     *
     * Iterates all lanelets and all centerline points. O(n) where n is
     * total centerline points across all lanelets.
     *
     * @note Does not consider vehicle heading.
     *
     * @param x  X position in map frame (metres).
     * @param y  Y position in map frame (metres).
     * @return   Pointer to nearest lanelet. Only nullptr if map is empty.
     */
  const Lanelet * getNearestLanelet(double x, double y) const;

  /**
     * @brief Returns all lanelets reachable from the given lanelet.
     *
     * @param id    Source lanelet ID.
     * @return      Vector of non-owning pointers to successor lanelets.
     *              Empty if id is not found or the lanelet has no successors.
     */
  std::vector<const Lanelet *> getSuccessors(const std::string & id) const;

  /**
     * @brief Returns all lanelets that lead into the given lanelet.
     *
     * @param id    Target lanelet ID.
     * @return      Vector of non-owning pointers to predecessor lanelets.
     *              Empty if id is not found or the lanelet has no predecessors.
     */
  std::vector<const Lanelet *> getPredecessors(const std::string & id) const;

  /**
     * @brief Returns all junctions in the map.
     *
     * @return  Const reference to the internal junction vector.
     */
  const std::vector<Junction> & getAllJunctions() const;

  /**
     * @brief Find a junction by its integer ID.
     *
     * @param junction_id  CARLA junction ID.
     * @return             Pointer to the junction, or nullptr if not found.
     */
  const Junction * getJunctionById(int junction_id) const;

  /**
     * @brief Returns true if the given lanelet is inside a junction.
     *
     * @param lanelet_id  Lanelet ID to check.
     * @return            True if lanelet.is_junction == true.
     *                    False if the lanelet is not found.
     */
  bool isInJunction(const std::string & lanelet_id) const;

private:
  /// @brief Parse the metadata section of hd_map.json into metadata_.
  void parseMetadata(const nlohmann::json & j);

  /// @brief Parse the lanelets array of hd_map.json into lanelets_.
  void parseLanelets(const nlohmann::json & j);

  /// @brief Parse the junctions array of hd_map.json into junctions_.
  void parseJunctions(const nlohmann::json & j);

  /// @brief Build O(1) hash-table lookup indexes after all parsing is done.
  void buildLookupTables();

  MapMetadata metadata_;             ///< Map-level metadata
  std::vector<Lanelet> lanelets_;    ///< All lanelets: HDMap owns these
  std::vector<Junction> junctions_;  ///< All junctions: HDMap owns these

  std::unordered_map<std::string, size_t> lanelet_index_;  ///< lanelet id  → index in lanelets_
  std::unordered_map<int, size_t> junction_index_;         ///< junction id → index in junctions_

  bool loaded_{false};  ///< True after a successful load()
};

}  // namespace hd_map

#endif  // HD_MAP__HD_MAP_HPP_
